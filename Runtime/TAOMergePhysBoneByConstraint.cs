using System.Collections.Generic;
using System.Linq;
using UnityEngine;
using VRC.Dynamics;
using VRC.SDKBase;

namespace TakuhoTech.TAO
{
    /// <summary>追従 PhysBone が従う「本体」の取得元。</summary>
    public enum TAOMainSource
    {
        /// <summary>対象の PhysBone の中から選んだものを本体にする。</summary>
        Existing,

        /// <summary>追従 PhysBone の平均的な位置に、新しい PhysBone を生成して本体にする。</summary>
        Generated,
    }

    /// <summary>本体 PhysBone の設定の取得元。</summary>
    public enum TAOSettingsSource
    {
        /// <summary>本体 PhysBone の設定をそのまま使う（既存の PhysBone を本体にする場合のみ）。</summary>
        KeepMain,

        /// <summary>追従 PhysBone の設定をまとめて使う。</summary>
        Generate,
    }

    /// <summary>
    /// 多数の PhysBone を VRC Rotation Constraint に置き換え、1 つの本体 PhysBone に追従させる。
    /// 本体以外の PhysBone（追従）は、ビルド時に削除される。
    /// </summary>
    [DisallowMultipleComponent]
    [AddComponentMenu("TAO/TAO Merge PhysBone By Constraint")]
    public class TAOMergePhysBoneByConstraint : MonoBehaviour, IEditorOnly
    {
        public TAOMainSource mainSource = TAOMainSource.Existing;

        /// <summary>本体の PhysBone（mainSource が Existing のとき）。physBones にも含まれる。</summary>
        public VRCPhysBoneBase mainPhysBone;

        /// <summary>対象の PhysBone。本体と、本体以外の追従 PhysBone を含む。</summary>
        public List<VRCPhysBoneBase> physBones = new List<VRCPhysBoneBase>();

        /// <summary>追従 PhysBone が本体の動きにどれだけ従うか。</summary>
        [Range(0f, 1f)] public float followStrength = 1f;

        public TAOSettingsSource settingsSource = TAOSettingsSource.KeepMain;

        /// <summary>手動で指定する PhysBone の設定。</summary>
        public TAOPhysBoneSettings settings = new TAOPhysBoneSettings();

        /// <summary>生成する PhysBone のボーン数（先端を含む）。自動なら追従 PhysBone の平均。</summary>
        public bool autoGeneratedBoneCount = true;

        [Min(2)] public int generatedBoneCount = 4;

        /// <summary>生成する PhysBone の親。自動なら追従 PhysBone の親の共通祖先。</summary>
        public bool autoGeneratedParent = true;

        public Transform generatedParent;

        /// <summary>重複と null を除いた追従 PhysBone。</summary>
        public List<VRCPhysBoneBase> GetFollowers()
        {
            var main = mainSource == TAOMainSource.Existing ? mainPhysBone : null;
            return physBones.Where(p => p != null && p != main).Distinct().ToList();
        }

        /// <summary>設定をまとめるときの元になる PhysBone。既存の PhysBone を本体にする場合は、本体自身も含む。</summary>
        public List<VRCPhysBoneBase> GetSettingsSources()
        {
            var sources = GetFollowers();
            if (mainSource == TAOMainSource.Existing && mainPhysBone != null) sources.Add(mainPhysBone);
            return sources;
        }

        /// <summary>生成する PhysBone のボーン数（先端を含む）。</summary>
        public int ResolveGeneratedBoneCount()
            => autoGeneratedBoneCount
                ? TAOPhysBoneTopology.AverageBoneCount(GetFollowers())
                : Mathf.Max(2, generatedBoneCount);

        /// <summary>生成する PhysBone の親。</summary>
        public Transform ResolveGeneratedParent(IEnumerable<VRCPhysBoneBase> followers)
            => !autoGeneratedParent && generatedParent != null
                ? generatedParent
                : TAOPhysBoneTopology.CommonParent(followers);

        public Transform ResolveGeneratedParent() => ResolveGeneratedParent(GetFollowers());

        /// <summary>本体の、回転するボーンの数。本体が未設定なら 0。</summary>
        public int MainRotatingBoneCount()
        {
            if (mainSource == TAOMainSource.Generated) return ResolveGeneratedBoneCount() - 1;
            return mainPhysBone != null ? TAOPhysBoneTopology.RotatingBoneCount(mainPhysBone) : 0;
        }

        /// <summary>本体のルートの親。追従 PhysBone の親と比べて、階層が同じかを調べるのに使う。</summary>
        public Transform MainParent()
        {
            if (mainSource == TAOMainSource.Generated) return ResolveGeneratedParent();
            return mainPhysBone != null ? TAOPhysBoneTopology.RootOf(mainPhysBone).parent : null;
        }

        /// <summary>実際に使われる設定の取得元。生成する場合は本体が無いので、常に Generate になる。</summary>
        public TAOSettingsSource EffectiveSettingsSource()
            => mainSource == TAOMainSource.Generated || settingsSource == TAOSettingsSource.Generate
                ? TAOSettingsSource.Generate
                : TAOSettingsSource.KeepMain;
    }
}
