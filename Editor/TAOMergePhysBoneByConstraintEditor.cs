using UnityEditor;
using UnityEngine;
using static TakuhoTech.TAO.Editor.TAOLocalization;

namespace TakuhoTech.TAO.Editor
{
    [CustomEditor(typeof(TAOMergePhysBoneByConstraint))]
    internal class TAOMergePhysBoneByConstraintEditor : UnityEditor.Editor
    {
        readonly TAOInspectorCache _cache = new TAOInspectorCache();
        readonly TAOPhysBoneSettingsGUI _settingsGUI = new TAOPhysBoneSettingsGUI();
        TAOTargetListGUI _targetList;

        SerializedProperty _mainSource;
        SerializedProperty _mainPhysBone;
        SerializedProperty _followStrength;
        SerializedProperty _settingsSource;
        SerializedProperty _settings;
        SerializedProperty _autoGeneratedBoneCount;
        SerializedProperty _generatedBoneCount;
        SerializedProperty _autoGeneratedParent;
        SerializedProperty _generatedParent;

        void OnEnable()
        {
            _targetList = new TAOTargetListGUI(this, serializedObject);
            _mainSource = serializedObject.FindProperty(nameof(TAOMergePhysBoneByConstraint.mainSource));
            _mainPhysBone = serializedObject.FindProperty(nameof(TAOMergePhysBoneByConstraint.mainPhysBone));
            _followStrength = serializedObject.FindProperty(nameof(TAOMergePhysBoneByConstraint.followStrength));
            _settingsSource = serializedObject.FindProperty(nameof(TAOMergePhysBoneByConstraint.settingsSource));
            _settings = serializedObject.FindProperty(nameof(TAOMergePhysBoneByConstraint.settings));
            _autoGeneratedBoneCount =
                serializedObject.FindProperty(nameof(TAOMergePhysBoneByConstraint.autoGeneratedBoneCount));
            _generatedBoneCount = serializedObject.FindProperty(nameof(TAOMergePhysBoneByConstraint.generatedBoneCount));
            _autoGeneratedParent =
                serializedObject.FindProperty(nameof(TAOMergePhysBoneByConstraint.autoGeneratedParent));
            _generatedParent = serializedObject.FindProperty(nameof(TAOMergePhysBoneByConstraint.generatedParent));
        }

        void OnDisable() => _cache.Dispose();

        public override void OnInspectorGUI()
        {
            var component = (TAOMergePhysBoneByConstraint)target;
            serializedObject.Update();

            // 計算結果の更新は Layout イベントだけで行い、Layout と Repaint で描画する内容をそろえる
            if (Event.current.type == EventType.Layout || !_cache.IsValid) _cache.Refresh(component);

            DrawLanguagePopup();

            _targetList.Draw(component, _cache);
            serializedObject.ApplyModifiedProperties();

            EditorGUILayout.Space();
            EditorGUILayout.PropertyField(_followStrength, new GUIContent(T("追従の強さ", "Follow Strength"),
                T("追従PhysBoneが、本体の動きにどれだけ従うか。下げると揺れが小さくなります",
                  "How strongly the follower PhysBones follow the main one. Lower values reduce the sway")));
            serializedObject.ApplyModifiedProperties();

            DrawErrors();
            TAOGUI.HorizontalLine();

            var isGenerated = _mainSource.enumValueIndex == (int)TAOMainSource.Generated;
            DrawSettings(component, isGenerated);
            TAOGUI.HorizontalLine();

            DrawStats(component);
            serializedObject.ApplyModifiedProperties();
        }

        // 変換できない設定のときだけ、メッセージを表示する
        void DrawErrors()
        {
            if (_cache.Followers.Count == 0)
            {
                EditorGUILayout.HelpBox(T("追従PhysBoneがありません。", "There are no follower PhysBones."),
                    MessageType.Error);
                return;
            }

            var isExisting = _mainSource.enumValueIndex == (int)TAOMainSource.Existing;
            if (isExisting && _mainPhysBone.objectReferenceValue == null)
            {
                EditorGUILayout.HelpBox(
                    T("本体が選択されていません。ボタンで本体を選択してください。",
                      "No main PhysBone is selected. Select one with the buttons."),
                    MessageType.Warning);
            }
        }

        void DrawSettings(TAOMergePhysBoneByConstraint component, bool isGenerated)
        {
            DrawSettingsSource(component, isGenerated);

            if (component.EffectiveSettingsSource() == TAOSettingsSource.Generate)
                _settingsGUI.SetSource(_cache.CombinedSettings, "settings.");
            else
                _settingsGUI.SetSource(component.mainPhysBone);

            _settingsGUI.Draw(_settings, () => DrawTransformExtras(isGenerated));
        }

        // 設定の取得元。生成する場合は本体が無いので、自動生成に固定する
        void DrawSettingsSource(TAOMergePhysBoneByConstraint component, bool isGenerated)
        {
            var label = new GUIContent(T("設定の取得元", "Settings Source"),
                T("各項目の「自動」で使う値の取得元です", "Where the values used by \"Auto\" come from"));
            var options = new[]
            {
                new GUIContent(T("本体の設定を維持", "Keep main settings"),
                    T("本体PhysBoneの値をそのまま使います", "Use the values of the main PhysBone as they are")),
                new GUIContent(T("自動生成", "Auto-generate"),
                    T("追従PhysBoneと本体の値をまとめて使います（ボーン数が違う場合は Pull・Stiffness・Max Angle を補正）",
                      "Combine the values of the follower PhysBones and the main one (Pull, Stiffness and Max Angle are corrected when the bone counts differ)")),
            };

            var rect = EditorGUI.PrefixLabel(EditorGUILayout.GetControlRect(), label);
            if (isGenerated)
            {
                using (new EditorGUI.DisabledScope(true))
                    GUI.Toolbar(rect, 1, options);
                return;
            }

            var current = component.EffectiveSettingsSource() == TAOSettingsSource.Generate ? 1 : 0;
            var picked = GUI.Toolbar(rect, current, options);
            if (picked != current)
            {
                _settingsSource.enumValueIndex =
                    (int)(picked == 1 ? TAOSettingsSource.Generate : TAOSettingsSource.KeepMain);
            }

            serializedObject.ApplyModifiedProperties();
        }

        // Transform セクションの先頭に追加する項目。
        // 生成する場合は親とボーン数、既存の PhysBone を本体にする場合は本体のボーン数を表示する
        void DrawTransformExtras(bool isGenerated)
        {
            if (!isGenerated)
            {
                var mainBoneCount = _mainPhysBone.objectReferenceValue != null ? _cache.MainRotatingBoneCount + 1 : 0;
                using (new EditorGUI.DisabledScope(true))
                {
                    EditorGUI.IntField(EditorGUILayout.GetControlRect(),
                        new GUIContent(T("本体のボーン数（先端を含む）", "Main Bone Count (including end bone)"),
                            T("本体PhysBoneのボーン数です", "The number of bones of the main PhysBone")),
                        mainBoneCount);
                }

                return;
            }

            DrawGeneratedParent();
            DrawGeneratedBoneCount();
        }

        void DrawGeneratedParent()
        {
            TAOGUI.SplitFieldAndPopup(EditorGUILayout.GetControlRect(), out var fieldRect, out var popupRect);
            var label = new GUIContent(T("生成先の親", "Parent of New PhysBone"),
                T("新しいPhysBoneを置く親のTransformです。自動: 追従PhysBoneの親の共通祖先",
                  "The parent Transform of the new PhysBone. Auto: the common ancestor of the follower PhysBones' parents"));

            if (_autoGeneratedParent.boolValue)
            {
                using (new EditorGUI.DisabledScope(true))
                    EditorGUI.ObjectField(fieldRect, label, _cache.AutoGeneratedParent, typeof(Transform), true);
            }
            else
            {
                EditorGUI.PropertyField(fieldRect, _generatedParent, label);
            }

            if (TAOGUI.AutoPopup(popupRect, _autoGeneratedParent.boolValue) == _autoGeneratedParent.boolValue) return;

            // 手動に切り替えたときは、自動の現在値から編集を始める
            if (_autoGeneratedParent.boolValue) _generatedParent.objectReferenceValue = _cache.AutoGeneratedParent;
            _autoGeneratedParent.boolValue = !_autoGeneratedParent.boolValue;
        }

        void DrawGeneratedBoneCount()
        {
            TAOGUI.SplitFieldAndPopup(EditorGUILayout.GetControlRect(), out var fieldRect, out var popupRect);
            var label = new GUIContent(
                T("生成PhysBoneのボーン数（先端を含む）", "New PhysBone Bone Count (including end bone)"),
                T("新しいPhysBoneのボーン数です。自動: 追従PhysBoneのボーン数の平均",
                  "The number of bones of the new PhysBone. Auto: the average bone count of the follower PhysBones"));

            if (_autoGeneratedBoneCount.boolValue)
            {
                using (new EditorGUI.DisabledScope(true))
                    EditorGUI.IntField(fieldRect, label, _cache.GeneratedBoneCount);
            }
            else
            {
                EditorGUI.PropertyField(fieldRect, _generatedBoneCount, label);
            }

            if (TAOGUI.AutoPopup(popupRect, _autoGeneratedBoneCount.boolValue) == _autoGeneratedBoneCount.boolValue)
                return;

            // 手動に切り替えたときは、自動の現在値から編集を始める
            if (_autoGeneratedBoneCount.boolValue)
                _generatedBoneCount.intValue = Mathf.Max(2, _cache.GeneratedBoneCount);
            _autoGeneratedBoneCount.boolValue = !_autoGeneratedBoneCount.boolValue;
        }

        // 変換による変化を、VRChat のパフォーマンス統計の名称で、増減として表示する。変化のない項目は表示しない。
        // 開閉の状態は、対象の PhysBone の見出しと同じく SerializedProperty の isExpanded で保持する
        void DrawStats(TAOMergePhysBoneByConstraint component)
        {
            _settings.isExpanded = EditorGUILayout.Foldout(_settings.isExpanded,
                T("パフォーマンス統計", "Performance Stats"), true);
            if (!_settings.isExpanded) return;

            EditorGUI.indentLevel++;
            foreach (var entry in TAOPerformanceStats.Calculate(component, _cache))
            {
                var sign = entry.Delta > 0 ? "+" : "";
                EditorGUILayout.LabelField($"{entry.Label}: {sign}{entry.Delta}", EditorStyles.miniLabel);
            }

            EditorGUI.indentLevel--;
        }
    }
}
