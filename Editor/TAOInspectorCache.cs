using System;
using System.Collections.Generic;
using UnityEditor;
using UnityEngine;
using VRC.Dynamics;

namespace TakuhoTech.TAO.Editor
{
    /// <summary>
    /// インスペクターで使う計算結果をまとめて保持する。再描画のたびに計算し直すと重いので、
    /// 入力が変わったときか、PhysBone 側の変更を拾うため一定時間ごとにだけ更新する。
    /// </summary>
    internal sealed class TAOInspectorCache : IDisposable
    {
        const double RefreshIntervalSeconds = 0.5;

        readonly Dictionary<VRCPhysBoneBase, int> _rotatingBoneCounts = new Dictionary<VRCPhysBoneBase, int>();
        TAOCombinedSettingsHolder _combinedHolder;
        bool _valid;
        int _inputKey;
        double _refreshedAt;

        public List<VRCPhysBoneBase> Followers { get; private set; } = new List<VRCPhysBoneBase>();

        public bool IsValid => _valid;

        /// <summary>本体の、回転するボーンの数。本体が未設定なら 0。</summary>
        public int MainRotatingBoneCount { get; private set; }

        public int GeneratedBoneCount { get; private set; }

        /// <summary>生成する PhysBone の親を「自動」にしたときの親。</summary>
        public Transform AutoGeneratedParent { get; private set; }

        /// <summary>本体のルートの親。</summary>
        public Transform MainParent { get; private set; }

        /// <summary>設定の取得元が「自動生成」のときの、まとめた設定。それ以外は null。</summary>
        public SerializedObject CombinedSettings { get; private set; }

        /// <summary>変換後の PhysBone が参照するコライダーの数。</summary>
        public int CollidersAfter { get; private set; }

        /// <summary>入力が変わっていたか、一定時間が過ぎていれば、計算し直す。Layout イベントで呼ぶ。</summary>
        public void Refresh(TAOMergePhysBoneByConstraint component)
        {
            var now = EditorApplication.timeSinceStartup;
            var key = ComputeInputKey(component);
            if (_valid && key == _inputKey && now - _refreshedAt < RefreshIntervalSeconds) return;

            _valid = true;
            _inputKey = key;
            _refreshedAt = now;

            Followers = component.GetFollowers();
            _rotatingBoneCounts.Clear();
            foreach (var physBone in component.GetSettingsSources())
                _rotatingBoneCounts[physBone] = TAOPhysBoneTopology.RotatingBoneCount(physBone);

            MainRotatingBoneCount = component.MainRotatingBoneCount();
            GeneratedBoneCount = component.ResolveGeneratedBoneCount();
            AutoGeneratedParent = TAOPhysBoneTopology.CommonParent(Followers);
            MainParent = component.MainParent();
            RefreshCombinedSettings(component);
        }

        public int RotatingBoneCountOf(VRCPhysBoneBase physBone)
            => _rotatingBoneCounts.TryGetValue(physBone, out var count)
                ? count
                : TAOPhysBoneTopology.RotatingBoneCount(physBone);

        public bool HasSameParentAsMain(VRCPhysBoneBase physBone)
            => MainParent == null || TAOPhysBoneTopology.RootOf(physBone).parent == MainParent;

        public void Dispose()
        {
            if (_combinedHolder != null) UnityEngine.Object.DestroyImmediate(_combinedHolder);
            _combinedHolder = null;
            CombinedSettings = null;
            _valid = false;
        }

        void RefreshCombinedSettings(TAOMergePhysBoneByConstraint component)
        {
            if (component.EffectiveSettingsSource() == TAOSettingsSource.Generate)
            {
                if (_combinedHolder == null)
                {
                    _combinedHolder = ScriptableObject.CreateInstance<TAOCombinedSettingsHolder>();
                    _combinedHolder.hideFlags = HideFlags.HideAndDontSave;
                    CombinedSettings = null;
                }

                // 取得元を切り替えると CombinedSettings だけが null になるので、ホルダーが残っていても作り直す
                if (CombinedSettings == null) CombinedSettings = new SerializedObject(_combinedHolder);

                _combinedHolder.settings = TAOPhysBoneSettings.Combine(component.GetSettingsSources(),
                    MainRotatingBoneCount);
                CombinedSettings.Update();
            }
            else
            {
                CombinedSettings = null;
            }

            CollidersAfter = CountCollidersAfter(component);
        }

        int CountCollidersAfter(TAOMergePhysBoneByConstraint component)
        {
            if (component.settings.IsManual("colliders")) return CountColliders(component.settings.colliders);
            if (_combinedHolder != null && CombinedSettings != null) return CountColliders(_combinedHolder.settings.colliders);
            return component.mainPhysBone != null ? CountColliders(component.mainPhysBone.colliders) : 0;
        }

        static int CountColliders(List<VRCPhysBoneColliderBase> colliders)
        {
            var count = 0;
            if (colliders == null) return count;
            foreach (var collider in colliders)
                if (collider != null) count++;
            return count;
        }

        static int ComputeInputKey(TAOMergePhysBoneByConstraint component)
        {
            var hash = new HashCode();
            hash.Add((int)component.mainSource);
            hash.Add((int)component.settingsSource);
            hash.Add(IdOf(component.mainPhysBone));
            hash.Add(component.autoGeneratedParent);
            hash.Add(IdOf(component.generatedParent));
            hash.Add(component.autoGeneratedBoneCount);
            hash.Add(component.generatedBoneCount);
            hash.Add(component.settings.IsManual("colliders"));
            foreach (var physBone in component.physBones) hash.Add(IdOf(physBone));
            return hash.ToHashCode();
        }

        static int IdOf(UnityEngine.Object target) => target != null ? target.GetInstanceID() : 0;
    }
}
