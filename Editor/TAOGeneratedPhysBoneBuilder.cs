using System.Collections.Generic;
using System.Linq;
using UnityEngine;
using VRC.Dynamics;
using VRC.SDK3.Dynamics.PhysBone.Components;

namespace TakuhoTech.TAO.Editor
{
    /// <summary>追従 PhysBone の平均的な位置・向きに、ボーン列と、それを動かす PhysBone を生成する。</summary>
    internal static class TAOGeneratedPhysBoneBuilder
    {
        /// <param name="parent">生成するボーン列の親。</param>
        /// <returns>生成したボーン列（先端を含む）。回転するボーンを持つ追従 PhysBone がなければ null。</returns>
        public static List<Transform> Build(TAOMergePhysBoneByConstraint component,
            List<VRCPhysBoneBase> followers, Transform parent)
        {
            var chains = followers
                .Select(TAOPhysBoneTopology.BoneChain)
                .Where(chain => chain.Count >= 2)
                .ToList();
            if (chains.Count == 0) return null;

            var boneCount = component.autoGeneratedBoneCount
                ? TAOPhysBoneTopology.AverageBoneCount(followers)
                : Mathf.Max(2, component.generatedBoneCount);

            var bones = CreateBones(chains, boneCount, parent);
            AddPhysBone(component, followers, bones[0], boneCount);
            return bones;
        }

        static List<Transform> CreateBones(List<List<Transform>> chains, int boneCount, Transform parent)
        {
            var bones = new List<Transform>();
            var previous = parent;
            for (var i = 0; i < boneCount; i++)
            {
                var progress = i / (boneCount - 1f);
                var position = Vector3.zero;
                var rotation = Quaternion.identity;
                for (var k = 0; k < chains.Count; k++)
                {
                    SampleChain(chains[k], progress, out var chainPosition, out var chainRotation);
                    position += chainPosition;
                    rotation = k == 0 ? chainRotation : Quaternion.Slerp(rotation, chainRotation, 1f / (k + 1));
                }

                position /= chains.Count;

                var bone = new GameObject(i == 0 ? "TAO Generated PhysBone" : $"TAO Generated PhysBone {i}").transform;
                bone.SetParent(previous, false);
                bone.SetPositionAndRotation(position, rotation);
                bones.Add(bone);
                previous = bone;
            }

            return bones;
        }

        static void AddPhysBone(TAOMergePhysBoneByConstraint component, List<VRCPhysBoneBase> followers,
            Transform root, int boneCount)
        {
            var physBone = root.gameObject.AddComponent<VRCPhysBone>();
            TAOPhysBoneSettings.Combine(followers, boneCount - 1).ApplyTo(physBone);
            physBone.rootTransform = null;
            physBone.ignoreTransforms = new List<Transform>();
            physBone.endpointPosition = Vector3.zero;
            component.settings.ApplyTo(physBone);
        }

        /// <summary>ボーン列を折れ線とみなし、全長に対する割合 progress の位置と向きを返す。</summary>
        static void SampleChain(List<Transform> chain, float progress, out Vector3 position, out Quaternion rotation)
        {
            var count = chain.Count;
            var lengths = new float[count];
            for (var i = 1; i < count; i++)
                lengths[i] = lengths[i - 1] + Vector3.Distance(chain[i].position, chain[i - 1].position);

            var total = lengths[count - 1];
            if (total < 1e-6f)
            {
                position = chain[0].position;
                rotation = chain[0].rotation;
                return;
            }

            var distance = progress * total;
            var segment = 1;
            while (segment < count - 1 && lengths[segment] < distance) segment++;

            var segmentLength = lengths[segment] - lengths[segment - 1];
            var fraction = segmentLength > 1e-6f
                ? Mathf.Clamp01((distance - lengths[segment - 1]) / segmentLength)
                : 0f;
            position = Vector3.Lerp(chain[segment - 1].position, chain[segment].position, fraction);
            rotation = Quaternion.Slerp(chain[segment - 1].rotation, chain[segment].rotation, fraction);
        }
    }
}
